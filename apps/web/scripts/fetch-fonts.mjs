/**
 * Fetches the typefaces we self-host and writes src/styles/fonts.css (ADR 0013).
 *
 * Both families are published under the SIL Open Font License 1.1, which permits bundling. We take
 * only the Latin subsets Google Fonts already produces, so the download stays around 100 KB total.
 *
 *   node apps/web/scripts/fetch-fonts.mjs
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const fontDir = join(here, '..', 'src', 'assets', 'fonts');
const cssPath = join(here, '..', 'src', 'styles', 'fonts.css');

// Fraunces as static instances (the variable cuts are five times the size): upright 600 for display,
// italic 600 for display, italic 500 for captions. Instrument Sans: variable weight for interface text.
const FAMILIES = [
  'family=Fraunces:ital,wght@0,600;1,500;1,600',
  'family=Instrument+Sans:wght@400..700',
].join('&');
const SUBSETS = new Set(['latin', 'latin-ext']);
const CHROME_UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36';
const LICENSES = [
  [
    'LICENSE-Fraunces.txt',
    'https://raw.githubusercontent.com/google/fonts/main/ofl/fraunces/OFL.txt',
  ],
  [
    'LICENSE-InstrumentSans.txt',
    'https://raw.githubusercontent.com/google/fonts/main/ofl/instrumentsans/OFL.txt',
  ],
];

const response = await fetch(`https://fonts.googleapis.com/css2?${FAMILIES}&display=swap`, {
  headers: { 'User-Agent': CHROME_UA },
});
if (!response.ok) throw new Error(`Google Fonts responded ${response.status}`);
const css = await response.text();

const blockPattern = /\/\* ([a-z-]+) \*\/\s*@font-face \{([^}]+)\}/g;
const faces = [];
for (const match of css.matchAll(blockPattern)) {
  const [, subset, body] = match;
  if (!SUBSETS.has(subset)) continue;
  const read = (pattern) => {
    const found = pattern.exec(body);
    if (!found) throw new Error(`Could not read ${pattern} from a font-face block`);
    return found[1].trim();
  };
  faces.push({
    subset,
    family: read(/font-family: '([^']+)'/),
    style: read(/font-style: (\w+)/),
    weight: read(/font-weight: ([\d ]+);/),
    url: read(/url\(([^)]+)\)/),
    range: read(/unicode-range: ([^;]+);/),
  });
}
if (faces.length === 0)
  throw new Error('No font-face blocks found; did Google change the CSS format?');

await mkdir(fontDir, { recursive: true });
let out =
  '/* Generated by scripts/fetch-fonts.mjs. Do not edit by hand.\n' +
  '   Fraunces and Instrument Sans are licensed under the SIL Open Font License 1.1; see the\n' +
  '   LICENSE files beside the font files. */\n\n';
let total = 0;
for (const face of faces) {
  const file = `${face.family.replace(/\s+/g, '')}-${face.style}-${face.weight.replace(/\s+/g, '_')}-${face.subset}.woff2`;
  const bytes = Buffer.from(await (await fetch(face.url)).arrayBuffer());
  await writeFile(join(fontDir, file), bytes);
  total += bytes.length;
  console.log(`${file}  ${(bytes.length / 1024).toFixed(1)} KB`);
  out +=
    `@font-face {\n  font-family: '${face.family}';\n  font-style: ${face.style};\n` +
    `  font-weight: ${face.weight};\n  font-display: swap;\n` +
    `  src: url('../assets/fonts/${file}') format('woff2');\n  unicode-range: ${face.range};\n}\n\n`;
}
await writeFile(cssPath, out);
console.log(`total ${(total / 1024).toFixed(1)} KB across ${faces.length} files`);

for (const [name, url] of LICENSES) {
  const license = await fetch(url);
  if (license.ok) await writeFile(join(fontDir, name), await license.text());
  else console.log(`license not fetched: ${name} (${license.status})`);
}
