export const GENRES: readonly Genre[] = DEFS.map(
  ([
    id,
    name,
    audiusName,
    description,
    hue,
    featured,
    energy,
    valence,
    danceability,
    acousticness,
    instrumentalness,
    tempo,
  ]) => ({
    id,
    name,
    description,
    hue,
    featured,
    providerNames: { audius: audiusName },
    vibe: vibe({ energy, valence, danceability, acousticness, instrumentalness, tempo }),
  }),
);

const BY_ID: ReadonlyMap<Id, Genre> = new Map(GENRES.map((genre) => [genre.id, genre]));
const BY_AUDIUS_NAME: ReadonlyMap<string, Genre> = new Map(
  GENRES.flatMap((genre) =>
    genre.providerNames.audius ? [[genre.providerNames.audius.toLowerCase(), genre]] : [],
  ),
);

export const FEATURED_GENRES: readonly Genre[] = GENRES.filter((genre) => genre.featured);

export function genreById(id: Id): Genre | undefined {
  return BY_ID.get(id);
}

export function genreIdForAudiusName(name: string | null | undefined): Id | null {
  if (!name) return null;
  return BY_AUDIUS_NAME.get(name.toLowerCase())?.id ?? null;
}

export function audiusNameForGenre(id: Id): string | null {
  return BY_ID.get(id)?.providerNames.audius ?? null;
}
